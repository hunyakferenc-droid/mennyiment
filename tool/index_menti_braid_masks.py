"""Index detached atlas contamination without changing any original PNG pixel.

The largest opaque core is the braid; tiny alpha halos can connect neighbouring
atlas tiles. A multi-source flood assigns original antialias pixels to their
nearest core. Only foreign cores and isolated fragments are excluded. No source
image is edited. Requires Pillow for development.
"""
from collections import deque
import hashlib
from pathlib import Path
import re

from PIL import Image

root = Path(__file__).resolve().parents[1]
asset = root / 'assets/images/menti_2_2/premium/hair.png'
alpha = Image.open(asset).getchannel('A')
catalog = (root / 'lib/menti_identity/menti_premium_atlas.dart').read_text()
entries = []
for family in ['boy', 'girl', 'neutral']:
    name = family + '-braid'
    match = re.search(r"'hair/" + name + r"': Rect.fromLTWH\((\d+),(\d+),(\d+),(\d+)\)", catalog)
    x, y, w, h = map(int, match.groups())
    data = alpha.crop((x, y, x + w, y + h)).tobytes()
    # Alpha 1..16 halos can connect adjacent atlas tiles. Separate opaque
    # cores first, then assign their original antialias pixels by an 8-neighbour
    # multi-source flood. Every >16 alpha pixel of the main core is retained.
    visited = bytearray(w * h)
    components = []
    def neighbours(n):
        px, py = n % w, n // w
        for yy in range(max(0, py - 1), min(h, py + 2)):
            for xx in range(max(0, px - 1), min(w, px + 2)):
                yield yy * w + xx
    for first in range(w * h):
        if visited[first] or data[first] <= 16:
            continue
        pending = [first]
        visited[first] = 1
        points = []
        while pending:
            n = pending.pop()
            points.append(n)
            for q in neighbours(n):
                if not visited[q] and data[q] > 16:
                    visited[q] = 1
                    pending.append(q)
        if len(points) >= 64:
            components.append(points)
    components.sort(key=len, reverse=True)
    labels = bytearray(w * h)
    queue = deque()
    for index, component in enumerate(components):
        for n in sorted(component):
            labels[n] = 1 if index == 0 else 2
            queue.append(n)
    while queue:
        n = queue.popleft()
        for q in neighbours(n):
            if data[q] and not labels[q]:
                labels[q] = labels[n]
                queue.append(q)
    main = {n for n in range(w * h) if labels[n] == 1}
    excluded = {n for n in range(w * h) if data[n] and labels[n] != 1}
    rectangles = []
    while excluded:
        first = min(excluded)
        pending = [first]
        excluded.remove(first)
        component = []
        while pending:
            n = pending.pop()
            component.append(n)
            for q in neighbours(n):
                if q in excluded:
                    excluded.remove(q)
                    pending.append(q)
        x1, y1 = min(p % w for p in component), min(p // w for p in component)
        x2, y2 = max(p % w for p in component) + 1, max(p // w for p in component) + 1
        if not any(yy * w + xx in main for yy in range(y1, y2) for xx in range(x1, x2)):
            rectangles.append((x1, y1, x2 - x1, y2 - y1))
        else:
            for yy in sorted({n // w for n in component}):
                row = sorted(n % w for n in component if n // w == yy)
                start = end = row[0]
                for xx in row[1:] + [w + 1]:
                    if xx != end + 1:
                        rectangles.append((start, yy, end - start + 1, 1))
                        start = xx
                    end = xx
    entries.append((name, w, h, rectangles))
    print(name, len(main), 'preserved main-component pixels;', sum(bool(v) for v in data) - len(main), 'detached pixels')
code = "// Generated by tool/index_menti_braid_masks.py; original pixels are unchanged.\n"
code += '// Source PNG SHA-256: ' + hashlib.sha256(asset.read_bytes()).hexdigest() + '\n'
code += "import 'dart:ui';\n\nclass MentiBraidIsolation {\n"
code += '  static const sourceSizes = <String, Size>{\n'
for name, w, h, rects in entries:
    code += f"    '{name}': Size({w}, {h}),\n"
code += '  };\n  static const sourceExclusions = <String, List<Rect>>{\n'
for name, w, h, rects in entries:
    code += f"    '{name}': [\n"
    code += ''.join(f'      Rect.fromLTWH({x}, {y}, {rw}, {rh}),\n' for x, y, rw, rh in rects)
    code += '    ],\n'
code += '''  };
  static final _cache = <String, Path>{};
  static final _windows = <String, Path>{};
  static Path window(String hair) => _windows.putIfAbsent(hair, () =>
      Path.combine(PathOperation.difference,
          Path()..addRect(const Rect.fromLTWH(0, 0, 1, 1)), exclusions(hair)));

  static Path exclusions(String hair) => _cache.putIfAbsent(hair, () {
    final size = sourceSizes[hair]!;
    final path = Path();
    for (final r in sourceExclusions[hair]!) {
      path.addRect(Rect.fromLTWH(r.left / size.width, r.top / size.height,
          r.width / size.width, r.height / size.height));
    }
    return path;
  });
}
'''
(root / 'lib/menti_identity/menti_braid_isolation.dart').write_text(code)
