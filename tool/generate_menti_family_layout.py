#!/usr/bin/env python3
"""Generate typed registration metadata from versioned nine-core art direction."""
import json
from pathlib import Path
spec=json.loads(Path('tool/menti_family_fits.json').read_text())
lines=["// Generated by tool/generate_menti_family_layout.py.","import 'package:flutter/material.dart';", "import 'menti_identity.dart';", "import 'menti_visual_catalog.dart';",'', '''class MentiPartFit {
  const MentiPartFit(this.sx, this.sy, this.dx, this.dy, this.px, this.py);
  final double sx, sy, dx, dy, px, py;
  Offset map(Offset point) => Offset((point.dx-px)*sx+px+dx, (point.dy-py)*sy+py+dy);
  Rect mapRect(Rect rect) => Rect.fromPoints(map(rect.topLeft), map(rect.bottomRight));
  Matrix4 matrix(double width, double height) => Matrix4.identity()
    ..translateByDouble((px*(1-sx)+dx)*width/320, (py*(1-sy)+dy)*height/400, 0, 1)
    ..scaleByDouble(sx, sy, 1, 1);
  static const identity = MentiPartFit(1,1,0,0,0,0);
}
class MentiFamilyLayout {
  MentiFamilyLayout(this.key);
  final String key;
  static const root = MentiVisualCatalog.root;
  factory MentiFamilyLayout.of(MentiIdentityProfile profile) {
    final family = MentiVisualCatalog.resolve('family', profile.visual.value('family')).id;
    final age = MentiVisualCatalog.resolve('age', profile.visual.value('age')).id;
    return MentiFamilyLayout('$family-$age');
  }
  String get core => '${root}identities/$key.png';
  MentiPartFit forField(String field) {
    final group = switch (field) {
      'face' => 'mouth',
      'eyes' || 'glasses' || 'detail' => 'eyes',
      'hair' || 'headwear' => 'head',
      'outfit' || 'style' || 'accent' || 'neck' || 'back' || 'held' => 'body',
      _ => '',
    };
    final fit = fits[key]?[group] ?? MentiPartFit.identity;
    if (field == 'held') return MentiPartFit(fit.sx.clamp(.85,1).toDouble(), fit.sy, fit.dx, fit.dy, fit.px, fit.py);
    return fit;
  }
  MentiPartFit forPath(String path) {
    if (path.endsWith('core/crown-cap.png')) return forField('headwear');
    for (final entry in const {'faces':'face', 'eyes':'eyes','hair':'hair','headwear':'headwear',
      'outfits':'outfit','styles':'style','accents':'accent'}.entries) {
      if (path.contains('/${entry.key}/')) return forField(entry.value);
    }
    if (path.contains('/accessories/')) {
      final id = path.split('/').last.replaceAll('.svg','');
      for (final field in ['glasses','neck','held','detail','back']) {
        if (MentiVisualCatalog.forField(field).any((o) => o.id==id)) return forField(field);
      }
    }
    return MentiPartFit.identity;
  }
  static const fits = <String, Map<String, MentiPartFit>>{''']
for key,item in spec.items():
 lines.append(f"    '{key}': {{")
 for group,vals in item['fits'].items():lines.append(f"      '{group}': MentiPartFit({','.join(map(str,vals))}),")
 lines.append('    },')
lines+=['  };','}']
Path('lib/menti_identity/menti_family_layout.dart').write_text('\n'.join(lines)+'\n')
print('Nine typed layouts generated')
