"""Read-only PNG metrics and reproducible Dart/provenance generation.
Never modifies any source or application image. Bounds come from alpha >=128;
all components are included to preserve detached accessory details.
"""
from pathlib import Path
import hashlib, json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
assets = ROOT / 'assets/images/menti_complete'
styles = [('base','alap'),('party','buli'),('festival','fesztival'),('sport','sport'),('business','uzleti'),('legendary','legendas')]
refs = {'boy': ('fiu', {'base':'F01','party':'F02','festival':'F03','sport':'F04','business':'F05','legendary':'F06'}), 'girl': ('lany', {'base':'L01','sport':'L02','business':'L03','festival':'L04','legendary':'L05','party':'L06'}), 'neutral': ('semleges', {'base':'S01','party':'S02','legendary':'S03','business':'S04','sport':'S05','festival':'S06'})}
basebounds = {'boy':(137,74,941,1390), 'girl':(90,0,1017,1418), 'neutral':(224,68,1001,1192)}
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
records = []
for family,(directory,ids) in refs.items():
    for style,original_name in styles:
        p = assets / f'{family}-{style}.png'
        if not p.exists(): continue
        original = ROOT / f'docs/images/menti-complete-looks/originals/{directory}/{original_name}.png'
        with Image.open(p) as im:
            assert im.mode == 'RGBA', p
            alpha = im.getchannel('A'); bbox = alpha.point(lambda a: 255 if a >=128 else 0).getbbox()
            assert bbox and alpha.getextrema()[0] == 0, p
            w,h = im.size
            bounds = basebounds[family] if style == 'base' else (max(0,bbox[0]-6), max(0,bbox[1]-6), min(w,bbox[2]+6), min(h,bbox[3]+6))
            edge = any(alpha.getpixel(xy) >128 for xy in [(0,0),(w-1,0),(0,h-1),(w-1,h-1)])
        records.append(dict(id=f'{family}-{style}-v1', family=family, style=style, reference=ids[style], asset=str(p.relative_to(ROOT)), original=str(original.relative_to(ROOT)), source_sha256=sha(original), asset_sha256=sha(p), width=w,height=h,bounds=bounds,minXp=200 if style=='legendary' else 0, corner_opaque=edge, procedure='unchanged approved RGBA source' if sha(p)==sha(original) else 'technical AI-assisted background cutout; derived candidate, not new owner approval', thumbnail=f'assets/images/menti_complete/thumbs/{family}-{style}.png'))
lines=["part of 'menti_collection_model.dart';",'', '// Generated by tool/build_collection_catalog.py from actual PNG assets.', 'const collectionLooks = <CompleteLook>[']
for r in records:
    lines.extend(["  CompleteLook(",f"    '{r['id']}', '{r['family']}', '{r['asset']}',",f"    Size({r['width']}, {r['height']}), Rect.fromLTRB({', '.join(map(str,r['bounds']))}),",f"    style: '{r['style']}', minXp: {r['minXp']}, reference: '{r['reference']}',",f"    thumbnail: '{r['thumbnail']}',",'  ),'])
lines.append('];')
(ROOT/'lib/menti_collection_catalog.dart').write_text('\n'.join(lines)+'\n')
(ROOT/'docs/collection/catalog-provenance.json').write_text(json.dumps(records, ensure_ascii=False, indent=2)+'\n')
print(f'{len(records)} real assets; {sum(r["minXp"]==0 for r in records)} free, {sum(r["minXp"]>0 for r in records)} XP')
