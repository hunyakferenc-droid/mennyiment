#!/usr/bin/env python3
"""Read unchanged reference PNGs and emit registration masks, never edited pixels.
Requires Pillow, numpy and scipy. Masks select original garments/skin/hair only.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image
from scipy import ndimage

ROOT=Path(__file__).resolve().parent.parent
# Artboard registrations match MentiReferenceRig. Hand windows isolate real hands.
FACES={
'boy':[(270,141,267,184),(837,87,234,205),(1434,90,252,218)],
'girl':[(381,115,208,194),(897,91,203,194),(1423,84,216,214)],
'neutral':[(303,109,241,180),(851,78,231,199),(1409,86,238,201)]}
REG={
'boy':[(130,320,(195,475,300,590),(510,475,590,592)),(700,285,(750,468,855,590),(1080,475,1170,590)),(1295,300,(1325,475,1443,590),(1665,475,1765,590))],
'girl':[(190,300,(280,462,370,575),(577,463,649,578)),(710,284,(772,461,867,575),(1096,461,1173,575)),(1260,294,(1306,460,1412,584),(1650,460,1735,582))],
'neutral':[(150,279,(229,483,318,585),(515,483,594,585)),(690,270,(767,450,855,575),(1054,451,1134,575)),(1235,278,(1307,473,1400,583),(1586,471,1677,583))],
}

def contours(mask):
    # Directed boundary edge tracing on a 2px grid; collinear points removed.
    mask=mask[::2,::2]; edges={}
    for y,x in zip(*np.where(mask)):
        for a,b,inside in [((x,y),(x+1,y),y>0 and mask[y-1,x]),((x+1,y),(x+1,y+1),x+1<mask.shape[1] and mask[y,x+1]),((x+1,y+1),(x,y+1),y+1<mask.shape[0] and mask[y+1,x]),((x,y+1),(x,y),x>0 and mask[y,x-1])]:
            if not inside: edges.setdefault(a,[]).append(b)
    paths=[]
    while edges:
        start=next(iter(edges)); p=start; points=[]
        while True:
            points.append(p); opts=edges.get(p)
            if not opts: break
            q=opts.pop()
            if not opts: del edges[p]
            p=q
            if p==start: break
        if len(points)<8: continue
        simplified=[]
        for i,b in enumerate(points):
            a,c=points[i-1],points[(i+1)%len(points)]
            if (b[0]-a[0])*(c[1]-b[1])!=(b[1]-a[1])*(c[0]-b[0]): simplified.append([int(b[0]*2),int(b[1]*2)])
        if len(simplified)>=4: paths.append(simplified)
    return paths

result={}
for fam,records in REG.items():
    data=np.array(Image.open(ROOT/f'assets/images/menti_2_2/reference/{fam}.png'))
    r,g,b,a=[data[:,:,i].astype(float) for i in range(4)]
    yy,xx=np.mgrid[:data.shape[0],:data.shape[1]]
    skin=(r>140)&(g>65)&(r>g*1.10)&(g>b*1.65)&(a>20)
    # Brown hair: source detail, not synthetic replacement geometry.
    brown=(r>g*1.20)&(g>b*1.18)&(a>20)&(r>35)
    for i,(origin,neck,left,right) in enumerate(records):
        age=['young','adult','veteran'][i]; key=f'{fam}-{age}'
        extent=(xx>=origin)&(xx<origin+520)
        clothes=(a>25)&~skin&extent&(yy>=neck)
        fx,fy,fw,fh=FACES[fam][i]
        face=((xx-fx-fw/2)/(fw/2))**2+((yy-fy-fh/2)/(fh/2))**2<=1
        gray=(abs(r-g)<28)&(abs(g-b)<28)&(r>75)&(xx>fx-50)&(xx<fx+fw+50)&(yy<fy+fh)
        headhair=(brown|gray)&~skin&~face&extent&(yy<neck+(90 if fam=='girl' else -10))
        # Preserve brows and facial wrinkles by retaining the entire face region.
        # Hair change draws the original skin underneath the new hair layer.
        large=ndimage.binary_opening(headhair,iterations=1)
        labs,n=ndimage.label(large)
        if n:
            sizes=ndimage.sum(large,labs,range(n+1)); keep=np.flatnonzero(sizes>300)
            large=ndimage.binary_fill_holes(np.isin(labs,keep)&(labs>0))&~face
        entry={'garments':contours(clothes),'hair':contours(large)}
        for kind,img in [('headSkin',data),('cleanHeadSkin',np.array(Image.open(ROOT/f'assets/images/menti_2_2/reference/{fam}-hairless.png')))]:
            rr,gg,bb,aa=[img[:,:1942,j].astype(float) for j in range(4)]
            headskin=(rr>125)&(gg>55)&(rr>gg*1.08)&(gg>bb*1.5)&(aa>20)&extent&(yy<neck+26)
            labels,n=ndimage.label(headskin)
            sizes=ndimage.sum(headskin,labels,range(n+1));sizes[0]=0
            component=labels==int(np.argmax(sizes))
            component=ndimage.binary_fill_holes(ndimage.binary_closing(component,iterations=2))
            entry[kind]=contours(component)
        for side,window in [('left',left),('right',right)]:
            x0,y0,x1,y1=window
            selected=skin&(xx>=x0)&(xx<x1)&(yy>=y0)&(yy<y1)
            selected=ndimage.binary_fill_holes(ndimage.binary_closing(selected,iterations=2))
            labs,n=ndimage.label(selected)
            if n:
                sizes=ndimage.sum(selected,labs,range(n+1)); sizes[0]=0
                selected=labs==int(np.argmax(sizes))
            entry[side+'Hand']=contours(selected)
        result[key]=entry
out=ROOT/'lib/menti_identity/menti_reference_masks.dart'
with out.open('w') as f:
    f.write("// Generated by tool/index_menti_reference_masks.py; original PNG pixels unchanged.\nimport 'dart:ui';\n\nclass MentiReferenceMasks {\n  static const contours = <String, Map<String, List<List<Offset>>>>{\n")
    for key,entry in result.items():
        f.write(f"    '{key}': {{\n")
        for name,paths in entry.items():
            f.write(f"      '{name}': [\n")
            for path in paths:
                f.write('        ['+','.join(f'Offset({x},{y})' for x,y in path)+'],\n')
            f.write('      ],\n')
        f.write('    },\n')
    f.write('  };\n}\n')
print('Nine reference mask registrations:',out.relative_to(ROOT),out.stat().st_size,'bytes')
