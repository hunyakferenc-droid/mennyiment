"""Index original generated PNG atlases without modifying their pixels.

Produces source rectangles for Flutter's drawImageRect, file integrity metadata,
and explicit stable-ID mappings. Re-run after intentionally changing source art.
"""
from pathlib import Path
from PIL import Image
import json,hashlib,zlib
root=Path(__file__).resolve().parents[1]
outfits=['basic','basic-alt','party','party-alt','sport','sport-alt','business','business-alt','festival','festival-alt','legendary','legendary-alt','street','street-alt','cozy','cozy-alt','explorer','explorer-alt','creative','creative-alt']
hair=[f'{f}-{s}' for f in ['boy','girl','neutral'] for s in ['crop','waves','curls','braid','bob','crest']]
features=[f'face:{s}' for s in ['cheerful','calm','playful','confident','sleepy','determined']]+[f'eyes:{s}' for s in ['round','wide','relaxed','sharp','blink','wink']]
groups={'bodies':(3,3,[f'{f}-{a}' for f in ['boy','girl','neutral'] for a in ['young','adult','veteran']]),'outfits':(5,4,outfits),'hair':(6,3,hair),'features':(6,2,features),'headwear':(3,3,['crown-cap','sport-cap','beanie','headphones','party-crown','hood','party-hat','beret','cowboy'])}
manifest={}; lines=["// Generated by tool/index_menti_premium_atlases.py; source pixels are unchanged.","import 'dart:ui';","class MentiPremiumAtlas {", "  static const root = 'assets/images/menti_2_2/premium/';",'  static const rects = <String, Rect>{']
for group,(cols,rows,ids) in groups.items():
 p=root/f'assets/images/menti_2_2/premium/{group}.png';im=Image.open(p).convert('RGBA');w,h=im.size
 cells={}
 for n,id in enumerate(ids):
  x,y=n%cols,n//cols
  cell=(round(x*w/cols),round(y*h/rows),round((x+1)*w/cols),round((y+1)*h/rows))
  if group=='outfits':
   bounds=[(0,312),(314,620),(622,927),(930,1254)]
   cell=(cell[0],bounds[y][0],cell[2],bounds[y][1])
  # Read alpha geometry only. Source assets are never cropped or re-encoded.
  alpha=im.getchannel('A').crop(cell).point(lambda v:255 if v>150 else 0)
  b=alpha.getbbox()
  if not b:raise ValueError((group,id,'empty'))
  rect=[cell[0]+b[0],cell[1]+b[1],b[2]-b[0],b[3]-b[1]]
  cells[id]=rect
  lines.append(f"    '{group}/{id}': Rect.fromLTWH({','.join(map(str,rect))}),")
 manifest[group]={'asset':str(p.relative_to(root)),'size':[w,h],'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'crc32':zlib.crc32(p.read_bytes()),'columns':cols,'rows':rows,'sprites':cells}
lines+=['  };','}']
(root/'lib/menti_identity/menti_premium_atlas.dart').write_text('\n'.join(lines)+'\n')
(root/'test/fixtures/menti_premium_atlases.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
